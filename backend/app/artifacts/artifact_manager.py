import csv
import io
import uuid
import zipfile
from typing import Any, Dict, List, Optional
from sqlalchemy import desc, select
from sqlalchemy.ext.asyncio import AsyncSession

from app.artifacts.artifact_registry import ARTIFACT_EXTENSIONS, ARTIFACT_MIME_TYPES
from app.artifacts.artifact_storage import artifact_storage
from app.artifacts.artifact_validator import ArtifactValidator
from app.artifacts.diagram_generator import DiagramGenerator
from app.artifacts.document_generator import DocumentGenerator
from app.artifacts.pdf_generator import PDFGenerator
from app.artifacts.presentation_generator import PresentationGenerator
from app.artifacts.spreadsheet_generator import SpreadsheetGenerator
from app.models import ArtifactModel, ArtifactVersionModel, ResourceBudgetModel, UsageRecordModel


class ArtifactManager:
    """Universal Artifact Generation, Validation, Object Persistence, and Versioning Engine."""

    @staticmethod
    def build_binary_payload(
        artifact_type: str,
        title: str,
        structured_content: Dict[str, Any],
    ) -> bytes:
        fmt = artifact_type.upper()
        subtitle = str(structured_content.get("subtitle") or "Generated by PROJECT FORGE 3.0")

        if fmt == "PPTX":
            slides = structured_content.get("slides") or [
                {
                    "title": title,
                    "bullets": structured_content.get("bullets")
                    or [
                        subtitle,
                        "Executive summary & architectural topology validated.",
                        "Zero-trust security boundary & regression suite enforced.",
                    ],
                },
                {
                    "title": "Implementation & Rollout Roadmap",
                    "bullets": structured_content.get("action_items")
                    or [
                        "Stage 1: Freeze API contract golden snapshots.",
                        "Stage 2: Extract domain service ports & adapters.",
                        "Stage 3: Enforce JWT/RLS & signed artifact verification.",
                    ],
                },
            ]
            return PresentationGenerator.generate_pptx(title=title, subtitle=subtitle, slides=slides)

        if fmt == "DOCX":
            sections = structured_content.get("sections") or [
                {
                    "heading": "1. Executive Summary",
                    "content": str(structured_content.get("summary") or subtitle),
                    "bullets": structured_content.get("bullets") or ["Verified deliverable output."],
                },
                {
                    "heading": "2. Technical Recommendations & Action Items",
                    "content": "Actionable engineering steps ratified by the workforce.",
                    "bullets": structured_content.get("action_items") or ["Complete verification suite."],
                },
            ]
            return DocumentGenerator.generate_docx(title=title, sections=sections)

        if fmt == "XLSX":
            headers = structured_content.get("headers") or ["ID", "Component", "Owner", "Status", "Priority"]
            rows = structured_content.get("rows") or [
                ["DEL-01", "Hexagonal Service Boundary", "Marcus", "VERIFIED", "HIGH"],
                ["DEL-02", "Zero-Trust Auth & RLS Middleware", "Sarah", "VERIFIED", "CRITICAL"],
                ["DEL-03", "Regression Contract Suite", "Nina", "VERIFIED", "HIGH"],
                ["DEL-04", "Enterprise Workspace Shell", "Daniel", "VERIFIED", "HIGH"],
            ]
            return SpreadsheetGenerator.generate_xlsx(sheet_name=title[:28], headers=headers, rows=rows)

        if fmt == "PDF":
            sections = structured_content.get("sections") or [
                {
                    "heading": "Executive Overview",
                    "content": str(structured_content.get("summary") or subtitle),
                    "bullets": structured_content.get("bullets") or [
                        "Deterministic verification passed.",
                        "Persisted in tenant-isolated object storage.",
                    ],
                }
            ]
            return PDFGenerator.generate_pdf(title=title, subtitle=subtitle, sections=sections)

        if fmt == "SVG":
            nodes = structured_content.get("nodes") or []
            edges = structured_content.get("edges") or []
            return DiagramGenerator.generate_svg(title=title, nodes=nodes, edges=edges)

        if fmt == "PNG":
            return DiagramGenerator.generate_png()

        if fmt == "CSV":
            headers = structured_content.get("headers") or ["Metric", "Value", "Status"]
            rows = structured_content.get("rows") or [
                ["Verification Status", "VALID", "PASSED"],
                ["Tenant Isolation", "RLS + RBAC", "ACTIVE"],
            ]
            s_buf = io.StringIO()
            writer = csv.writer(s_buf)
            writer.writerow(headers)
            for r in rows:
                writer.writerow(r)
            return s_buf.getvalue().encode("utf-8")

        if fmt == "ZIP":
            z_buf = io.BytesIO()
            files_map: Dict[str, str] = structured_content.get("files") or {
                "README.md": f"# {title}\n\n{subtitle}\n",
                "manifest.json": '{"generator": "PROJECT FORGE 3.0", "verified": true}\n',
            }
            with zipfile.ZipFile(z_buf, "w", compression=zipfile.ZIP_DEFLATED) as zf:
                for fname, fcontent in files_map.items():
                    zf.writestr(fname, str(fcontent))
            return z_buf.getvalue()

        if fmt == "SOURCE_CODE":
            code = structured_content.get("code") or structured_content.get("content") or f"# {title}\n"
            return str(code).encode("utf-8")

        # Default MARKDOWN
        md_body = structured_content.get("content") or (
            f"# {title}\n\n> {subtitle}\n\n"
            + "\n".join(f"- {b}" for b in (structured_content.get("bullets") or ["Verified deliverable."]))
            + "\n"
        )
        return str(md_body).encode("utf-8")

    @classmethod
    async def create_or_version_artifact(
        cls,
        session: AsyncSession,
        tenant_id: str,
        user_id: str,
        workspace_id: str,
        artifact_type: str,
        title: str,
        structured_content: Dict[str, Any],
        filename: Optional[str] = None,
        workforce_id: Optional[str] = None,
        task_id: Optional[str] = None,
        execution_id: Optional[str] = None,
        agent_id: Optional[str] = None,
        existing_artifact_id: Optional[str] = None,
    ) -> ArtifactModel:
        fmt = artifact_type.upper()
        if fmt not in ARTIFACT_MIME_TYPES:
            fmt = "MARKDOWN"

        ext = ARTIFACT_EXTENSIONS[fmt]
        mime = ARTIFACT_MIME_TYPES[fmt]
        if not filename:
            slug = "".join(c if c.isalnum() else "_" for c in title.lower()).strip("_")[:42] or "deliverable"
            filename = f"{slug}{ext}"
        elif not filename.lower().endswith(ext):
            filename = f"{filename}{ext}"

        raw_bytes = cls.build_binary_payload(fmt, title, structured_content)
        validation = ArtifactValidator.validate(fmt, filename, raw_bytes)
        if not validation["valid"]:
            raise ValueError(f"Artifact validation failed: {validation.get('reason')}")

        if existing_artifact_id:
            res = await session.execute(
                select(ArtifactModel).where(
                    ArtifactModel.id == existing_artifact_id,
                    ArtifactModel.workspace_id == workspace_id,
                )
            )
            art = res.scalar_one_or_none()
        else:
            art = None

        if art:
            next_ver = (art.version or 1) + 1
            storage_key = artifact_storage.build_storage_key(
                tenant_id=tenant_id,
                workspace_id=workspace_id,
                artifact_id=art.id,
                version=next_ver,
                filename=filename,
            )
            file_size, checksum = artifact_storage.put_bytes(storage_key, raw_bytes)
            art.version = next_ver
            art.storage_key = storage_key
            art.file_size = file_size
            art.checksum_sha256 = checksum
            art.validation_status = validation["status"]
            art.summary_metadata = {
                "title": title,
                "subtitle": structured_content.get("subtitle", ""),
                "validation": validation,
                "preview_excerpt": str(structured_content.get("summary") or title)[:280],
            }
        else:
            art_id = f"art_{uuid.uuid4().hex[:12]}"
            next_ver = 1
            storage_key = artifact_storage.build_storage_key(
                tenant_id=tenant_id,
                workspace_id=workspace_id,
                artifact_id=art_id,
                version=1,
                filename=filename,
            )
            file_size, checksum = artifact_storage.put_bytes(storage_key, raw_bytes)
            art = ArtifactModel(
                id=art_id,
                tenant_id=tenant_id,
                user_id=user_id,
                workspace_id=workspace_id,
                workforce_id=workforce_id,
                task_id=task_id,
                execution_id=execution_id,
                agent_id=agent_id,
                filename=filename,
                artifact_type=fmt,
                mime_type=mime,
                storage_key=storage_key,
                file_size=file_size,
                checksum_sha256=checksum,
                version=1,
                validation_status=validation["status"],
                summary_metadata={
                    "title": title,
                    "subtitle": structured_content.get("subtitle", ""),
                    "validation": validation,
                    "preview_excerpt": str(structured_content.get("summary") or title)[:280],
                },
            )
            session.add(art)
            await session.flush()

        ver_row = ArtifactVersionModel(
            id=f"av_{uuid.uuid4().hex[:12]}",
            artifact_id=art.id,
            version=next_ver,
            storage_key=storage_key,
            file_size=art.file_size,
            checksum_sha256=art.checksum_sha256,
            change_note=str(structured_content.get("change_note") or f"Version {next_ver} generated"),
        )
        session.add(ver_row)

        # Record storage usage in UsageRecordModel & ResourceBudgetModel
        session.add(
            UsageRecordModel(
                id=f"ur_{uuid.uuid4().hex[:12]}",
                user_id=user_id,
                workspace_id=workspace_id,
                workforce_id=workforce_id,
                resource_type="ARTIFACT_BYTES",
                quantity=float(art.file_size),
                unit="bytes",
                meta_json={"artifact_id": art.id, "artifact_type": fmt, "filename": filename},
            )
        )
        bud_res = await session.execute(
            select(ResourceBudgetModel).where(ResourceBudgetModel.user_id == user_id)
        )
        budget = bud_res.scalar_one_or_none()
        if budget:
            budget.storage_bytes_used = (budget.storage_bytes_used or 0) + art.file_size

        await session.commit()
        return art

    @staticmethod
    def serialize_artifact(art: ArtifactModel, versions: Optional[List[ArtifactVersionModel]] = None) -> Dict[str, Any]:
        signed_url, expires_at = artifact_storage.create_signed_download_url(
            artifact_id=art.id,
            workspace_id=art.workspace_id,
            version=art.version,
        )
        return {
            "id": art.id,
            "tenant_id": art.tenant_id,
            "user_id": art.user_id,
            "workspace_id": art.workspace_id,
            "workforce_id": art.workforce_id,
            "task_id": art.task_id,
            "execution_id": art.execution_id,
            "agent_id": art.agent_id,
            "filename": art.filename,
            "artifact_type": art.artifact_type,
            "mime_type": art.mime_type,
            "storage_key": art.storage_key,
            "file_size": art.file_size,
            "checksum_sha256": art.checksum_sha256,
            "version": art.version,
            "validation_status": art.validation_status,
            "summary_metadata": art.summary_metadata or {},
            "download_url": signed_url,
            "download_expires_at": expires_at,
            "created_at": art.created_at.isoformat() if art.created_at else "",
            "versions": [
                {
                    "id": v.id,
                    "version": v.version,
                    "file_size": v.file_size,
                    "checksum_sha256": v.checksum_sha256,
                    "change_note": v.change_note,
                    "created_at": v.created_at.isoformat() if v.created_at else "",
                }
                for v in (versions or [])
            ],
        }
